//2-D Array operations
let arr = [[10, 20], [30, 40], [50, 60]];
arr.push(60);  //push
console.log("Push:", arr);
arr.pop();  //pop
console.log("pop:", arr);
arr.unshift(5);  //unshift
console.log("unshift:", arr);
arr.shift();  //shift
console.log("Shift:", arr);
arr.splice(1, 2, 99, 88);  //splice
console.log("Splice:", arr);